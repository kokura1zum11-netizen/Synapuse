def vary_jrrp_text(text: str, probability=0.3) -> str:
    for word, variants in JRRP_SYNONYMS.items():
        if word in text and random.random() < probability:
            text = text.replace(word, random.choice(variants), 1)
    return text

def get_daily_rp_value(user_id: str) -> int:
    today = datetime.now().strftime("%Y%m%d")
    seed_str = f"{user_id}{today}"
    hash_hex = hashlib.md5(seed_str.encode()).hexdigest()[:8]
    seed = int(hash_hex, 16)
    return (seed % 100) + 1

